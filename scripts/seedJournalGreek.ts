async function main() {
  for (const post of POSTS) {
    const now = new Date();
    const publishedAt = new Date(now.getTime() - post.daysAgo * 24 * 60 * 60 * 1000).toISOString();
    const { data: existing } = await supabase.from("journal_posts").select("id").eq("slug", post.slug).maybeSingle();

    const row = {
      slug: post.slug,
      title: post.title,
      excerpt: post.excerpt,
      content_html: post.contentHtml,
      featured_image_url: post.image,
      author_name: AUTHOR,
      category: post.category,
      tags: post.tags,
      featured: post.featured,
      status: "published",
      published_at: publishedAt,
      robots: "index,follow",
    };

    if (existing) {
      const { error } = await supabase.from("journal_posts").update(row).eq("id", existing.id);
      if (error) throw error;
      console.log(`Updated: ${post.slug}`);
    } else {
      const { error } = await supabase.from("journal_posts").insert(row);
      if (error) throw error;
      console.log(`Inserted: ${post.slug}`);
    }
  }
  console.log("Done.");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
